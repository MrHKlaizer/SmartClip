// ║                                                                              ║
// ║  Что сохраняется: папки, закрепы (с тегами; картинки — прямо внутри JSON,  ║
// ║  чтобы бэкап работал на другом ПК), профили, основные настройки.           ║
// ║  Видео/аудио-закрепы сохраняются как ссылки на файл (они слишком большие). ║
// ╚══════════════════════════════════════════════════════════════════════════════╝

#pragma once

#include <QJsonObject>
#include <QString>

class Database;

namespace Backup {

struct ImportResult {
    bool    ok = false;         // false — файл не прочитался / не JSON
    QString error;              // Текст ошибки, если ok == false
    int     pinsAdded = 0;      // Сколько закрепов добавлено
    int     pinsSkipped = 0;    // Сколько пропущено (такие уже есть)
    int     profilesAdded = 0;
    int     profilesSkipped = 0;
    bool    settingsApplied = false;
    bool    mainHotkeyChanged = false;
};

// Собрать все данные в JSON-объект.
QJsonObject exportAll(Database *db);

// Записать exportAll() в файл. Возвращает false, если файл не записался.
bool exportToFile(Database *db, const QString &path, QString *error = nullptr);

// Прочитать файл и добавить данные в БД. Уже существующие закрепы и
// профили НЕ дублируются — повторный импорт того же файла ничего не меняет.
ImportResult importFromFile(Database *db, const QString &path);

// Автобэкап: если включён в настройках и прошло достаточно дней — сохранить
// smartclip_backup_ГГГГ-ММ-ДД.json в выбранную папку. Хранятся 10 последних.
void runAutoBackupIfDue(Database *db);

} // namespace Backup
