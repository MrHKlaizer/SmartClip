// ╔══════════════════════════════════════════════════════════════════════════════╗
// ║  AdminMode.h — «Работать в окнах администратора»                          ║
// ║                                                                              ║
// ║  Windows не пускает обычные программы в окна, открытые от администратора   ║
// ║  (защита UIPI): хоткей Win+V до SmartClip не доходит, вставка блокируется.  ║
// ║                                                                              ║
// ║  Решение: задача в Планировщике Windows с наивысшими правами запускает    ║
// ║  маленького помощника (AdminHelper.h) — без окна UAC при каждом входе.     ║
// ║  Сам SmartClip всегда работает как обычный пользователь: всё, что он       ║
// ║  открывает, не получает прав администратора. Окно UAC появляется только    ║
// ║  один раз — при включении настройки (создание задачи).                     ║
// ╚══════════════════════════════════════════════════════════════════════════════╝
#pragma once

#include <string>

namespace AdminMode {

// Аргументы командной строки
constexpr const char *ARG_CREATE_TASK = "--create-admin-task"; // Создать задачу (уже от админа) и выйти
constexpr const char *ARG_HELPER      = "--admin-helper";      // Запущены Планировщиком: помощник
constexpr const char *ARG_ELEVATED    = "--elevated";          // Так задачу создавали до 2.4 — тоже помощник

bool isElevated();        // Процесс работает с правами администратора
bool canElevate();        // Пользователь — администратор (можно повысить права)
// Процесс с правами админа, но у пользователя есть и обычные (UAC включён):
// можно перезапуститься обычным пользователем
bool canDropToUser();
std::wstring exePath();         // Полный путь к SmartClip.exe
std::wstring currentUserSid();  // SID текущего пользователя (строкой)

// Создать задачу Планировщика. Вызывается в процессе с правами админа.
bool createTask();
// Удалить задачу (нужны права админа; без них — молча ничего не делает).
void deleteTask();
// Запустить помощника через задачу (с правами админа). false — задачи нет или ошибка.
bool runTask();

// Из обычного процесса: показать UAC и создать задачу. false — отказ или ошибка.
bool requestCreateTask();
// Из процесса админа: запустить SmartClip как обычного пользователя (через Проводник).
void launchAsUser();

} // namespace AdminMode
